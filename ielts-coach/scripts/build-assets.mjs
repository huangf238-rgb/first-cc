// Bundles public/ into src/assets.gen.ts so the Worker serves the web app itself
// (no separate static-asset upload step).
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "public");
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8" };
const out = {};
for (const f of fs.readdirSync(dir)) {
  const ext = path.extname(f);
  if (!types[ext]) continue;
  out["/" + f] = { type: types[ext], body: fs.readFileSync(path.join(dir, f), "utf8") };
}
fs.writeFileSync(path.join(root, "src", "assets.gen.ts"),
  "// Generated by scripts/build-assets.mjs. Do not edit.\nexport const ASSETS: Record<string, { type: string; body: string }> = " + JSON.stringify(out) + ";\n");
console.log("bundled", Object.keys(out).length, "files");
